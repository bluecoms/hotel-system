// ===========================================================
// Hotel Admin — i18n Initialization (2025-10-15 안정화판)
// -----------------------------------------------------------
// 목적:
//  1. 한국어(i18n) 메시지 로드 및 글로벌 t() 지원
//  2. 모든 컴포넌트/서비스에서 `import { t } from '@/i18n'` 바로 사용 가능
//  3. messages.ko.ts만 존재해도 동작하도록 기본 locale=ko 설정
// ===========================================================

import { createI18n } from 'vue-i18n'
import ko from './messages.ko'

// ---------------------------------------------------------------------------
// i18n 인스턴스 생성
// ---------------------------------------------------------------------------
export const i18n = createI18n({
  legacy: false,
  globalInjection: true,
  locale: 'ko',
  fallbackLocale: 'ko',
  messages: { ko },
})

// ---------------------------------------------------------------------------
// 글로벌 t() 함수 (전역 접근용)
// ---------------------------------------------------------------------------
// 모든 곳에서 import { t } from '@/i18n' 으로 번역 호출 가능
export const t = (key: string, params?: Record<string, any>) =>
  i18n.global.t(key, params)
